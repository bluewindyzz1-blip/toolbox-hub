def update_object(text, slug, values):
    pattern = re.compile(r'(^  \{\s*slug: "' + re.escape(slug) + r'".*?)(?=^  \{\s*slug:|^\];)', re.S | re.M)
    match = pattern.search(text)
    if not match:
        raise SystemExit(f'guide not found: {slug}')
    block = match.group(1)
    for key, value in values.items():
        literal = json.dumps(value, ensure_ascii=False)
        field = re.compile(r'\b' + key + r':\s*"(?:\\.|[^"\\])*"')
        replacement = f'{key}: {literal}'
        if field.search(block):
            block = field.sub(replacement, block, count=1)
        else:
            anchor = re.search(r'(\n\s*intro:)', block)
            if not anchor:
                raise SystemExit(f'cannot insert {key}: {slug}')
            block = block[:anchor.start()] + f'\n    {key}: {literal},' + block[anchor.start():]
    return text[:match.start(1)] + block + text[match.end(1):]

